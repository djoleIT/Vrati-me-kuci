const LangContext = createContext({ lang: "sr", setLang: () => {}, t: dict.sr });

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState("sr");

  useEffect(() => {
    const saved = window.localStorage.getItem("vmk_lang");
    if (saved && dict[saved]) setLang(saved);
  }, []);

  function changeLang(code) {
    setLang(code);
    window.localStorage.setItem("vmk_lang", code);
  }

  return (
    <LangContext.Provider
      value={{
        lang,
        setLang: changeLang,
        t: { ...dict.sr, ...dict[lang] },
        pricePromo: formatDin(SITE.pricePromo),
        priceRegular: formatDin(SITE.priceRegular),
        shipping: formatDin(SITE.shipping),
        total: formatDin(SITE.pricePromo + SITE.shipping),
        contactEmail: SITE.contactEmail,
      }}
    >
      {children}
    </LangContext.Provider>
  );
}

export function useI18n() {
  return useContext(LangContext);
}
